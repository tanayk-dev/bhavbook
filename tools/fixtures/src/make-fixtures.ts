// Builds anonymised fixtures from the local, gitignored broker exports (plan step S2).
// Usage: `pnpm fixtures:make` → builds into a temp directory, scans it, then replaces packages/adapters/fixtures.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import * as XLSX from 'xlsx';
import { loadDenylist, scanPaths } from './pii-scan.js';
import { sanitizeFileName, scrubJournalCsv } from './scrub.js';
import { REPO_ROOT, SOURCES, type FixtureSource } from './sources.js';
import { scrubSpreadsheet } from './xls-patch.js';

export interface FixtureResult {
  readonly broker: FixtureSource['broker'];
  readonly kind: string;
  readonly format: FixtureSource['format'];
  readonly sourcePath: string;
  readonly outputPath: string;
  /** CSV: one entry per changed line; spreadsheets: `Sheet!A1` per changed cell, `#Prop` per property. */
  readonly replaced: readonly string[];
  readonly bytes: number;
  readonly sha256: string;
  /** CSV: line count; spreadsheets: sheet count. */
  readonly parts: number;
}

function scrubCsv(source: FixtureSource, input: Buffer): { output: Buffer; replaced: string[]; parts: number } {
  const result = scrubJournalCsv(input, {
    ...(source.replaceColumns ? { replaceColumns: source.replaceColumns } : {}),
    expectMetadata: source.metadata === true,
  });
  const lineChanges = Array.from({ length: result.changedLines }, (_, index) => `line-change-${index + 1}`);
  return { output: result.bytes, replaced: lineChanges, parts: result.bytes.toString('latin1').split(/\r\n|\r|\n/).length };
}

function scrubFile(source: FixtureSource, input: Buffer, denyTerms: readonly string[]): { output: Buffer; replaced: string[]; parts: number } {
  if (source.format === 'csv') return scrubCsv(source, input);
  const { output, changes } = scrubSpreadsheet(input, source.format, denyTerms);
  return { output, replaced: [...changes], parts: 0 };
}

/** Scrubs every source file into `outDir/<broker>/<kind>/<sanitised name>`. */
export function buildFixtures(exportsDir: string, outDir: string, denyTerms: readonly string[] = []): FixtureResult[] {
  const seen = new Set<string>();
  return SOURCES.flatMap((source) => {
    const dir = path.join(exportsDir, source.dir);
    if (!existsSync(dir)) return [];
    return readdirSync(dir)
      .filter((name) => path.extname(name).toLowerCase() === `.${source.format}`)
      .map((name) => {
        const sourcePath = path.join(dir, name);
        const { output, replaced, parts } = scrubFile(source, readFileSync(sourcePath), denyTerms);
        const outputPath = path.join(outDir, source.broker, source.kind, sanitizeFileName(name));
        if (seen.has(outputPath)) throw new Error(`two sources map to the same fixture name in ${source.broker}/${source.kind}`);
        seen.add(outputPath);
        mkdirSync(path.dirname(outputPath), { recursive: true });
        writeFileSync(outputPath, output);
        const sheets = source.format === 'csv' ? parts : countSheets(output);
        return {
          broker: source.broker,
          kind: source.kind,
          format: source.format,
          sourcePath,
          outputPath,
          replaced,
          bytes: output.length,
          sha256: createHash('sha256').update(output).digest('hex'),
          parts: sheets,
        };
      });
  });
}

function countSheets(bytes: Buffer): number {
  return XLSX.read(bytes, { bookSheets: true }).SheetNames.length;
}

function manifest(results: readonly FixtureResult[], outDir: string): string {
  const header = [
    '# Broker fixtures',
    '',
    'Anonymised copies of real broker exports, generated by `pnpm fixtures:make` (tools/fixtures).',
    'Do not edit by hand. Every file passes `pnpm pii:scan`. CSVs are byte-identical to the originals except for',
    'the replaced values; legacy `.xls` files are patched in place, so every byte outside the replaced strings is kept.',
    '',
    '| Broker | Kind | File | Format | Lines / sheets | Changed | SHA-256 |',
    '| :--- | :--- | :--- | :--- | ---: | ---: | :--- |',
  ];
  const rows = results.map((result) => {
    const file = path.relative(outDir, result.outputPath).replaceAll('\\', '/');
    return `| ${result.broker} | ${result.kind} | \`${file}\` | ${result.format} | ${result.parts} | ${result.replaced.length} | \`${result.sha256.slice(0, 12)}\` |`;
  });
  return [...header, ...rows, ''].join('\n');
}

function main(): void {
  const exportsDir = path.join(REPO_ROOT, 'docs', 'broker-exports');
  const outDir = path.join(REPO_ROOT, 'packages', 'adapters', 'fixtures');
  const denylist = loadDenylist();
  // Fail closed: names have no reliable pattern, so the local denylist is the only sure way to catch the
  // account holder's own name. Never generate fixtures without it.
  if (denylist.length === 0) {
    console.error(
      'No PII denylist found. Create ~/.bhavbook-pii-denylist (or set BHAVBOOK_PII_DENYLIST) with your name and ' +
        'client IDs, one per line. It stays outside the repo.',
    );
    process.exitCode = 1;
    return;
  }
  const staging = mkdtempSync(path.join(tmpdir(), 'bhavbook-fixtures-'));
  try {
    const results = buildFixtures(exportsDir, staging, denylist);
    writeFileSync(path.join(staging, 'MANIFEST.md'), manifest(results, staging));
    const findings = scanPaths([staging], denylist);
    if (findings.length > 0) {
      console.error(`PII scan failed with ${findings.length} finding(s); existing fixtures were left untouched.`);
      process.exitCode = 1;
      return;
    }
    rmSync(outDir, { recursive: true, force: true });
    cpSync(staging, outDir, { recursive: true });
    for (const result of results) {
      console.log(`${result.broker}/${result.kind}: ${result.replaced.length} change(s)`);
    }
    console.log(`Wrote ${results.length} fixture(s); PII scan OK (with local denylist of ${denylist.length} term(s)).`);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
